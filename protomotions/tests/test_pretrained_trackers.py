# The per-joint action scale the shipped g1-bones-deploy weights (2026-08-10) trained
# with, from the directory's old resolved_configs.yaml. Commit a347b28b1 (2026-10-15)
# later changed make_bm_pd_action_config to effort_fraction * effort_limit / stiffness
# with effort_fraction defaulting to 0.25, and the public mlp_bm_l2c2.py uses that
# default -- a quarter of this scale. The regen spec restores it with
# effort_fraction=1.0; this literal pins the exact values so that drift (or any other
# change to the action scale) cannot slip back into the shipped bundle unnoticed. The
# band check in the MuJoCo test is only a NaN/offset sanity guard; this is the pin.
