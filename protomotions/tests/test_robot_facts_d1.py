"""D1 robot-facts invariants: physics parameters, gains, registry, strictness.

``test_physics_parameters_unchanged_every_backend`` is the owner's merge
condition: it proves that resolving every robot through the new
``control_hz`` / ``SimulatorParams.humanoid`` / ``fps=None`` path reproduces
main-next's per-backend blocks field for field (fps, the decimation derived from
control_hz, substeps, every PhysX field including the gpu_* capacities, and every
Newton and MuJoCo field).

The fixture ``fixtures/robot_facts_d1_baseline.json`` was generated by resolving
every robot on main-next (captured, not retyped) and verified identical to a
fresh main-next capture. To regenerate it, resolve ``robot_config(name)`` for the
six robots on a main-next checkout and dump ``control.control_info`` and
``simulation_params`` (with the old ``decimation`` field) to JSON.
"""

import json
from pathlib import Path

import pytest

from protomotions.robot_configs.base import (
    ControlConfig,
    HUMANOID_ISAACGYM,
    HUMANOID_ISAACLAB,
    RobotConfig,
    SimulatorParams,
)
from protomotions.robot_configs.factory import robot_config, registered_robot_names
from protomotions.components.pose_lib import ControlInfo, extract_control_info
from protomotions.simulator.isaaclab.config import (
    IsaacLabSimParams,
    IsaacLabPhysXParams,
)
from protomotions.simulator.mujoco.config import MujocoSimParams

_FIXTURE = json.loads(
    (Path(__file__).parent / "fixtures" / "robot_facts_d1_baseline.json").read_text()
)
_ROBOTS = ("amp", "g1", "h1_2", "smpl", "smplx", "soma23")
_BACKENDS = ("isaacgym", "isaaclab", "newton", "mujoco")
_CHAIN = str(Path(__file__).parent / "fixtures" / "sensor_chain.xml")


def _same(got, want) -> bool:
    """True if two optional numbers are equal (None==None, floats bit-for-bit)."""
    if got is None or want is None:
        return got is None and want is None
    return repr(float(got)) == repr(float(want))


@pytest.mark.parametrize("name", _ROBOTS)
def test_physics_parameters_unchanged_every_backend(name):
    """Every resolved per-backend block matches main-next field for field (merge condition)."""
    cfg = robot_config(name)
    hz = cfg.control_hz
    for backend in _BACKENDS:
        block = getattr(cfg.simulation_params, backend)
        expected = _FIXTURE[name]["sim"][backend]
        assert (
            block.fps == expected["fps"]
        ), f"{name}.{backend}.fps {block.fps} != {expected['fps']}"
        assert block.fps // hz == expected["decimation"], (
            f"{name}.{backend} derived decimation {block.fps // hz} "
            f"!= today's {expected['decimation']}"
        )
        assert not hasattr(
            block, "decimation"
        ), f"{name}.{backend} still carries a decimation field"
        for key, exp_val in expected.items():
            if key == "decimation":
                continue  # derived, checked above
            if isinstance(exp_val, dict):  # physx / flex sub-blocks
                nested = getattr(block, key)
                for field_name, field_val in exp_val.items():
                    got = getattr(nested, field_name)
                    assert (
                        got == field_val
                    ), f"{name}.{backend}.{key}.{field_name} {got} != {field_val}"
            else:
                got = getattr(block, key)
                assert got == exp_val, f"{name}.{backend}.{key} {got} != {exp_val}"


@pytest.mark.parametrize("name", _ROBOTS)
def test_control_table_gains_unchanged(name):
    """Resolved gains match main-next bit-for-bit; amp's limits are the one declared change."""
    cfg = robot_config(name)
    for joint, ci in cfg.control.control_info.items():
        exp = _FIXTURE[name]["gains"][joint]
        for field_name in ("stiffness", "damping", "armature", "friction"):
            got, want = getattr(ci, field_name), exp[field_name]
            assert _same(got, want), f"{name}.{joint}.{field_name} {got!r} != {want!r}"
        if name == "amp":
            # AMP's MJCF declares no actuator ranges; D1 sets effort 1000 /
            # velocity 100 for every DOF (amp is in no parity scenario).
            assert (
                ci.effort_limit == 1000.0 and ci.velocity_limit == 100
            ), f"amp.{joint} limits {ci.effort_limit}/{ci.velocity_limit}"
        else:
            for field_name in ("effort_limit", "velocity_limit"):
                got, want = getattr(ci, field_name), exp[field_name]
                assert _same(
                    got, want
                ), f"{name}.{joint}.{field_name} {got!r} != {want!r}"


def test_registered_robot_names_are_the_sorted_stems():
    """The registry is the directory: sorted module stems minus the infrastructure modules."""
    assert registered_robot_names() == _ROBOTS


def test_unknown_robot_is_refused_with_the_registry_listed():
    """robot_config refuses an unregistered name before importing anything."""
    with pytest.raises(ValueError, match="unknown robot 'does_not_exist'"):
        robot_config("does_not_exist")


def test_module_must_define_exactly_one_direct_robotconfig(monkeypatch):
    """robot_config refuses a module with zero or two direct-RobotConfig classes."""
    import types
    from protomotions.robot_configs import factory

    def _fake_module(n_classes):
        module = types.ModuleType("protomotions.robot_configs.faker")
        for index in range(n_classes):
            module.__dict__[f"C{index}"] = type(f"C{index}", (RobotConfig,), {})
        return module

    monkeypatch.setattr(factory, "registered_robot_names", lambda: ("faker",))
    for n_classes in (0, 2):
        monkeypatch.setattr(
            factory.importlib,
            "import_module",
            lambda name, n=n_classes: _fake_module(n),
        )
        with pytest.raises(
            TypeError, match="exactly one class whose direct base is RobotConfig"
        ):
            factory.robot_config("faker")


def test_control_info_require_returns_or_refuses():
    """require() returns a set value, raises on None, and refuses friction (asset-owned)."""
    ci = ControlInfo(stiffness=5.0, effort_limit=None)
    assert ci.require("stiffness") == 5.0
    with pytest.raises(ValueError, match="effort_limit is not set"):
        ci.require("effort_limit")
    with pytest.raises(TypeError, match="friction is asset-owned"):
        ControlInfo(friction=0.1).require("friction")


def test_control_config_refuses_non_controlinfo_overrides():
    """override_control_info values must be ControlInfo, not dict."""
    with pytest.raises(TypeError, match="must be ControlInfo, not dict"):
        ControlConfig(override_control_info={"joint": {"stiffness": 1.0}})


def test_extract_control_info_refuses_a_pattern_matching_no_joint():
    """An override pattern that matches no joint of the asset is a mistake."""
    with pytest.raises(ValueError, match="matches no joint"):
        extract_control_info(
            _CHAIN, override_control_info={"no_such_joint": ControlInfo(stiffness=1.0)}
        )


def test_extract_control_info_refuses_an_unclaimed_joint():
    """Every joint must be claimed by an override or asset-default pattern."""
    with pytest.raises(ValueError, match="claimed by no override"):
        extract_control_info(
            _CHAIN, override_control_info={"waist": ControlInfo(stiffness=1.0)}
        )


def test_asset_default_joints_suppresses_the_unclaimed_refusal():
    """A joint under asset_default_joints keeps the MJCF values with no override."""
    info = extract_control_info(
        _CHAIN,
        override_control_info={"waist": ControlInfo(stiffness=1.0)},
        asset_default_joints=("elbow",),
    )
    assert info["waist"].stiffness == 1.0
    assert info["elbow"].stiffness is None


def test_control_hz_override_re_derives_derived_physics():
    """Overriding control_hz on a robot whose physics was derived re-derives it at the new rate."""
    g1 = robot_config("g1", control_hz=25)
    assert g1.control_hz == 25
    assert g1.simulation_params.isaacgym.fps == 50  # 25 * 2
    assert g1.simulation_params.isaaclab.fps == 100  # 25 * 4
    assert g1.simulation_params.mujoco.fps == 500  # 25 * 20
    # A rate that does not divide the 50 Hz-derived fps now just works.
    assert robot_config("g1", control_hz=30).simulation_params.isaacgym.fps == 60


def test_control_hz_override_keeps_explicit_physics_and_checks_divisibility():
    """A robot with explicit per-backend fps keeps it; an incompatible control_hz is refused naming the block."""
    smpl = robot_config("smpl", control_hz=30)
    assert smpl.simulation_params.mujoco.fps == 960  # explicit, kept
    with pytest.raises(ValueError, match="is not a multiple of control_hz"):
        robot_config("smpl", control_hz=7)  # explicit mujoco fps 960 % 7 != 0


def test_fps_unset_or_nonpositive_is_refused():
    """A hand-built SimulatorParams whose fps is unset or non-positive is refused with a clear message."""
    unset = SimulatorParams.humanoid(50)
    unset.isaacgym.fps = None
    with pytest.raises(ValueError, match="fps is not set"):
        robot_config("g1", simulation_params=unset)
    nonpositive = SimulatorParams.humanoid(50)
    nonpositive.mujoco.fps = 0
    with pytest.raises(ValueError, match="must be a positive integer"):
        robot_config("g1", simulation_params=nonpositive)


def test_humanoid_fills_fps_from_control_hz_and_keeps_explicit_fps():
    """fps derives from control_hz when unset and is kept when explicit; a passed block replaces the template wholesale; templates are not mutated."""
    assert HUMANOID_ISAACLAB.fps is None and HUMANOID_ISAACGYM.fps is None
    params = SimulatorParams.humanoid(
        30,
        isaaclab=IsaacLabSimParams(
            physx=IsaacLabPhysXParams(num_position_iterations=16)
        ),
        mujoco=MujocoSimParams(fps=900),
    )
    assert params.isaaclab.fps == 120  # None -> 30 * 4 substeps
    assert params.isaaclab.physx.num_position_iterations == 16  # kept
    assert params.mujoco.fps == 900  # explicit, honoured
    assert params.isaacgym.fps == 60  # 30 * 2 from the template
    # A passed block REPLACES the template wholesale (no field-level merge): the
    # PhysX fields it leaves unset are the class defaults, not the humanoid
    # template's tuned 8/4/1. To change one field off the tuning, pass
    # dataclasses.replace(HUMANOID_ISAACLAB, ...) instead of a fresh block.
    default_physx = IsaacLabPhysXParams()
    assert (
        default_physx.num_velocity_iterations
        != HUMANOID_ISAACLAB.physx.num_velocity_iterations
    )
    assert (
        params.isaaclab.physx.num_velocity_iterations
        == default_physx.num_velocity_iterations
    )
    assert (
        params.isaaclab.physx.max_depenetration_velocity
        == default_physx.max_depenetration_velocity
    )
    # The shared template is not mutated by the copy humanoid() makes.
    assert HUMANOID_ISAACLAB.physx.num_position_iterations == 8
